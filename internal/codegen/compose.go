func kotlinColor(val string) string {
	if strings.HasPrefix(val, "#") {
		hex := strings.TrimPrefix(val, "#")
		switch len(hex) {
		case 3:
			hex = "FF" + strings.Repeat(string(hex[0]), 2) + strings.Repeat(string(hex[1]), 2) + strings.Repeat(string(hex[2]), 2)
		case 6:
			hex = "FF" + hex
		case 8:
		default:
			return "Color.Unspecified"
		}
		return "Color(0x" + strings.ToUpper(hex) + ")"
	}
	if hex, ok := kotlinColorHex[strings.ToLower(strings.ReplaceAll(val, "_", ""))]; ok {
		return "Color(" + hex + ")"
	}
	return "Color.Unspecified"
}

// checkComposeSupport rejects features the preview target cannot render
// instead of silently dropping them from the output.
func checkComposeSupport(app *ast.AppNode) error {
	var firstErr error
	fail := func(line int, format string, args ...any) {
		if firstErr == nil {
			msg := fmt.Sprintf(format, args...)
			if line > 0 {
				msg = fmt.Sprintf("line %d: %s", line, msg)
			}
			firstErr = fmt.Errorf("compose target: %s", msg)
		}
	}
	var walkWidget func(w ast.WidgetNode)
	walkWidget = func(w ast.WidgetNode) {
		switch w.Kind {
		case "image":
			fail(w.Line, "image is not supported in the compose target yet (needs an image-loading library)")
		}
		for _, act := range w.Actions {
			walkAction(act, fail)
		}
		for _, ch := range w.Children {
			walkWidget(ch)
		}
	}
	for _, sc := range app.Screens {
		if sc.AppBar != nil {
			for _, ch := range sc.AppBar.Children {
				walkWidget(ch)
			}
		}
		if sc.FAB != nil {
			for _, act := range sc.FAB.Actions {
				walkAction(act, fail)
			}
		}
		for _, w := range sc.Widgets {
			walkWidget(w)
		}
	}
	return firstErr
}

func walkAction(act ast.ActionNode, fail func(int, string, ...any)) {
	switch act.Kind {
	case "http_get", "http_post", "json_get", "storage_set", "storage_get":
		fail(act.Line, "%s is not supported in the compose target yet", act.Kind)
	}
	for _, sub := range act.ThenActions {
		walkAction(sub, fail)
	}
	for _, sub := range act.ElseActions {
		walkAction(sub, fail)
	}
}

