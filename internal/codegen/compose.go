// Code generation for the Kotlin Jetpack Compose target.
//
// The compose target is a preview: it renders every screen with
// state-based switching (no Navigation component), the widget subset
// listed in the README, and the action subset that has a Compose
// equivalent. Anything else (HTTP, storage, drawer, network images)
// fails at transpile time with a clear message instead of being
// silently dropped. Generated code needs the material-icons-extended
// artifact for Icons.Filled.*.
package codegen

import (
	"fmt"
	"strings"

	"github.com/gapk-lang/gapk/internal/ast"
	"github.com/gapk-lang/gapk/internal/strlit"
	"github.com/gapk-lang/gapk/internal/validate"
)

type composeGen struct {
	states       map[string]string
	dropdownIdx  int
	firstScreen  string
	screenTitles map[string]bool
	inDrawer     bool
}

func GenerateKotlinCompose(app *ast.AppNode) (string, error) {
	if err := validate.ValidateApp(app); err != nil {
		return "", err
	}
	if err := checkComposeSupport(app); err != nil {
		return "", err
	}
	g := &composeGen{
		states:       map[string]string{},
		screenTitles: map[string]bool{},
	}
	for _, st := range app.States {
		g.states[st.Name] = st.Kind
	}
	for _, sc := range app.Screens {
		g.screenTitles[sc.Title] = true
	}
	if len(app.Screens) > 0 {
		g.firstScreen = app.Screens[0].Title
	}

	var out strings.Builder
	out.WriteString(fmt.Sprintf("package %s\n\n", app.PackageName))
	out.WriteString("// Generated by gapk (compose preview). Requires:\n")
	out.WriteString("//   androidx.compose.material:material-icons-extended (Icons.Filled.*)\n\n")
	out.WriteString("import android.os.Bundle\n")
	out.WriteString("import android.widget.Toast\n")
	out.WriteString("import androidx.activity.ComponentActivity\n")
	out.WriteString("import androidx.activity.compose.setContent\n")
	out.WriteString("import androidx.compose.foundation.background\n")
	out.WriteString("import androidx.compose.foundation.clickable\n")
	out.WriteString("import androidx.compose.foundation.layout.*\n")
	out.WriteString("import androidx.compose.foundation.lazy.grid.GridCells\n")
	out.WriteString("import androidx.compose.foundation.lazy.grid.LazyVerticalGrid\n")
	out.WriteString("import androidx.compose.foundation.rememberScrollState\n")
	out.WriteString("import androidx.compose.foundation.shape.CircleShape\n")
	out.WriteString("import androidx.compose.foundation.verticalScroll\n")
	out.WriteString("import androidx.compose.material.icons.Icons\n")
	out.WriteString("import androidx.compose.material.icons.filled.*\n")
	out.WriteString("import androidx.compose.material3.*\n")
	out.WriteString("import androidx.compose.runtime.*\n")
	out.WriteString("import androidx.compose.ui.Alignment\n")
	out.WriteString("import androidx.compose.ui.Modifier\n")
	out.WriteString("import androidx.compose.ui.draw.clip\n")
	out.WriteString("import androidx.compose.ui.graphics.Color\n")
	out.WriteString("import androidx.compose.ui.platform.LocalContext\n")
	out.WriteString("import androidx.compose.ui.text.font.FontWeight\n")
	out.WriteString("import androidx.compose.ui.unit.dp\n")
	out.WriteString("import androidx.compose.ui.unit.sp\n")
	out.WriteString("import kotlinx.coroutines.launch\n\n")

	out.WriteString("class MainActivity : ComponentActivity() {\n")
	out.WriteString("    override fun onCreate(savedInstanceState: Bundle?) {\n")
	out.WriteString("        super.onCreate(savedInstanceState)\n")
	out.WriteString("        setContent {\n")
	out.WriteString("            MaterialTheme {\n")
	out.WriteString("                Surface(modifier = Modifier.fillMaxSize()) {\n")
	out.WriteString(fmt.Sprintf("                    %sApp()\n", SanitizeIdent(app.AppName)))
	out.WriteString("                }\n")
	out.WriteString("            }\n")
	out.WriteString("        }\n")
	out.WriteString("    }\n")
	out.WriteString("}\n\n")

	out.WriteString("@OptIn(ExperimentalMaterial3Api::class)\n")
	out.WriteString("@Composable\n")
	out.WriteString(fmt.Sprintf("fun %sApp() {\n", SanitizeIdent(app.AppName)))
	out.WriteString("    val context = LocalContext.current\n")
	if len(app.Screens) > 0 {
		out.WriteString(fmt.Sprintf("    var currentScreen by remember { mutableStateOf(%s) }\n", strlit.Quoted(app.Screens[0].Title)))
	}
	out.WriteString("\n")

	for _, st := range app.States {
		switch st.Kind {
		case "string":
			out.WriteString(fmt.Sprintf("    var %s by remember { mutableStateOf(%s) }\n", st.Name, strlit.Quoted(st.Value)))
		case "list":
			var quoted []string
			for _, item := range st.ListItems {
				quoted = append(quoted, strlit.Quoted(item))
			}
			out.WriteString(fmt.Sprintf("    val %s = remember { mutableStateListOf(%s) }\n", st.Name, strings.Join(quoted, ", ")))
		default:
			out.WriteString(fmt.Sprintf("    var %s by remember { mutableStateOf(%s) }\n", st.Name, st.Value))
		}
	}
	if len(app.States) > 0 {
		out.WriteString("\n")
	}

	if len(app.Screens) > 0 {
		out.WriteString("    when (currentScreen) {\n")
		for _, sc := range app.Screens {
			g.renderComposeScreen(&out, sc)
		}
		out.WriteString("    }\n")
	}

	out.WriteString("}\n")
	return out.String(), nil
}

func (g *composeGen) renderComposeScreen(out *strings.Builder, sc ast.ScreenNode) {
	out.WriteString(fmt.Sprintf("        %s -> {\n", strlit.Quoted(sc.Title)))
	if sc.Drawer != nil {
		out.WriteString("            val drawerState = rememberDrawerState(initialValue = DrawerValue.Closed)\n")
		out.WriteString("            val scope = rememberCoroutineScope()\n")
		out.WriteString("            ModalNavigationDrawer(\n")
		out.WriteString("                drawerState = drawerState,\n")
		out.WriteString("                drawerContent = {\n")
		out.WriteString("                    ModalDrawerSheet {\n")
		g.inDrawer = true
		for _, ch := range sc.Drawer.Children {
			g.renderComposeWidget(out, ch, "                        ")
		}
		g.inDrawer = false
		out.WriteString("                    }\n")
		out.WriteString("                }\n")
		out.WriteString("            ) {\n")
		g.renderComposeScaffold(out, sc, "                ")
		out.WriteString("            }\n")
	} else {
		g.renderComposeScaffold(out, sc, "            ")
	}
	out.WriteString("        }\n")
}

func (g *composeGen) renderComposeScaffold(out *strings.Builder, sc ast.ScreenNode, ind string) {
	out.WriteString(ind + "Scaffold(\n")
	if sc.AppBar != nil {
		out.WriteString(ind + "    topBar = {\n")
		out.WriteString(ind + "        TopAppBar(\n")
		out.WriteString(fmt.Sprintf("%s            title = { Text(text = %s) },\n", ind, strlit.StringExpr(sc.AppBar.TextExpr)))
		if sc.Drawer != nil {
			out.WriteString(ind + "            navigationIcon = {\n")
			out.WriteString(ind + "                IconButton(onClick = { scope.launch { drawerState.open() } }) {\n")
			out.WriteString(ind + "                    Icon(imageVector = Icons.Filled.Menu, contentDescription = null)\n")
			out.WriteString(ind + "                }\n")
			out.WriteString(ind + "            },\n")
		}
		if len(sc.AppBar.Children) > 0 {
			out.WriteString(ind + "            actions = {\n")
			for _, ch := range sc.AppBar.Children {
				g.renderComposeWidget(out, ch, ind+"                ")
			}
			out.WriteString(ind + "            }\n")
		}
		out.WriteString(ind + "        )\n")
		out.WriteString(ind + "    },\n")
	}
	if sc.FAB != nil {
		out.WriteString(ind + "    floatingActionButton = {\n")
		out.WriteString(ind + "        FloatingActionButton(onClick = {\n")
		g.renderComposeActions(out, sc.FAB.Actions, ind+"            ")
		out.WriteString(ind + "        }) {\n")
		out.WriteString(fmt.Sprintf("%s            Icon(imageVector = Icons.Filled.%s, contentDescription = null)\n", ind, kotlinIconName(exprSingleValue(sc.FAB.TextExpr))))
		out.WriteString(ind + "        }\n")
		out.WriteString(ind + "    },\n")
	}
	if sc.BotNav != nil && len(sc.BotNav.Children) > 0 {
		out.WriteString(ind + "    bottomBar = {\n")
		out.WriteString(ind + "        NavigationBar {\n")
		for _, item := range sc.BotNav.Children {
			out.WriteString(ind + "            NavigationBarItem(\n")
			out.WriteString(fmt.Sprintf("%s                selected = currentScreen == %s,\n", ind, strlit.Quoted(item.BindState)))
			out.WriteString(fmt.Sprintf("%s                onClick = { currentScreen = %s },\n", ind, strlit.Quoted(item.BindState)))
			out.WriteString(fmt.Sprintf("%s                icon = { Icon(imageVector = Icons.Filled.%s, contentDescription = null) },\n", ind, kotlinIconName(item.Placeholder)))
			out.WriteString(fmt.Sprintf("%s                label = { Text(%s) }\n", ind, strlit.Quoted(exprSingleValue(item.TextExpr))))
			out.WriteString(ind + "            )\n")
		}
		out.WriteString(ind + "        }\n")
		out.WriteString(ind + "    },\n")
	}
	out.WriteString(ind + ") { innerPadding ->\n")
	out.WriteString(ind + "    Column(\n")
	out.WriteString(ind + "        modifier = Modifier.padding(innerPadding).padding(16.dp).fillMaxSize(),\n")
	out.WriteString(ind + "        verticalArrangement = Arrangement.spacedBy(8.dp)\n")
	out.WriteString(ind + "    ) {\n")
	for _, w := range sc.Widgets {
		g.renderComposeWidget(out, w, ind+"        ")
	}
	out.WriteString(ind + "    }\n")
	out.WriteString(ind + "}\n")
}

func (g *composeGen) renderComposeWidget(out *strings.Builder, w ast.WidgetNode, indent string) {
	switch w.Kind {
	case "column", "container", "listview":
		mods := ""
		if w.Kind == "container" {
			mods = g.composeContainerModifier(w)
		}
		out.WriteString(fmt.Sprintf("%sColumn(modifier = Modifier%s, verticalArrangement = Arrangement.spacedBy(8.dp)) {\n", indent, mods))
		for _, child := range w.Children {
			g.renderComposeWidget(out, child, indent+"    ")
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "row":
		out.WriteString(fmt.Sprintf("%sRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {\n", indent))
		for _, child := range w.Children {
			g.renderComposeWidget(out, child, indent+"    ")
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "stack":
		out.WriteString(fmt.Sprintf("%sBox {\n", indent))
		for _, child := range w.Children {
			g.renderComposeWidget(out, child, indent+"    ")
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "scroll":
		out.WriteString(fmt.Sprintf("%sColumn(modifier = Modifier.verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(8.dp)) {\n", indent))
		for _, child := range w.Children {
			g.renderComposeWidget(out, child, indent+"    ")
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "center":
		out.WriteString(fmt.Sprintf("%sBox(contentAlignment = Alignment.Center, modifier = Modifier.fillMaxWidth()) {\n", indent))
		g.renderComposeSingleChild(out, w.Children, indent+"    ")
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "expanded":
		flex := w.Props["flex"]
		if flex == "" {
			flex = "1"
		}
		out.WriteString(fmt.Sprintf("%sBox(modifier = Modifier.weight(%s)) {\n", indent, flex+".f"))
		g.renderComposeSingleChild(out, w.Children, indent+"    ")
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "padding":
		pad := w.Props["all"]
		if pad == "" {
			pad = "12"
		}
		out.WriteString(fmt.Sprintf("%sBox(modifier = Modifier.padding(%s)) {\n", indent, kotlinDp(pad)))
		g.renderComposeSingleChild(out, w.Children, indent+"    ")
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "card":
		out.WriteString(fmt.Sprintf("%sCard(modifier = Modifier.fillMaxWidth()) {\n", indent))
		out.WriteString(fmt.Sprintf("%s    Column(modifier = Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {\n", indent))
		for _, child := range w.Children {
			g.renderComposeWidget(out, child, indent+"        ")
		}
		out.WriteString(fmt.Sprintf("%s    }\n%s}\n", indent, indent))

	case "list_for":
		out.WriteString(fmt.Sprintf("%sfor (%s in %s) {\n", indent, w.IteratorVar, w.BindState))
		for _, child := range w.Children {
			g.renderComposeWidget(out, child, indent+"    ")
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "gridview":
		cols := w.Props["cols"]
		if cols == "" {
			cols = w.Props["cross"] // alias: gridview [cross: 2]
		}
		if cols == "" {
			cols = "2"
		}
		out.WriteString(fmt.Sprintf("%sLazyVerticalGrid(columns = GridCells.Fixed(%s)) {\n", indent, cols))
		for _, child := range w.Children {
			out.WriteString(fmt.Sprintf("%s    item {\n", indent))
			g.renderComposeWidget(out, child, indent+"        ")
			out.WriteString(fmt.Sprintf("%s    }\n", indent))
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "text":
		style := g.composeTextStyle(w)
		out.WriteString(fmt.Sprintf("%sText(text = %s%s)\n", indent, strlit.StringExpr(w.TextExpr), style))

	case "badge":
		out.WriteString(fmt.Sprintf("%sAssistChip(onClick = {}, label = { Text(%s) })\n", indent, strlit.StringExpr(w.TextExpr)))

	case "avatar":
		rad := w.Props["radius"]
		if rad == "" {
			rad = "20"
		}
		out.WriteString(fmt.Sprintf("%sBox(modifier = Modifier.size(%s).clip(CircleShape).background(MaterialTheme.colorScheme.primaryContainer), contentAlignment = Alignment.Center) {\n", indent, kotlinDp(rad)))
		out.WriteString(fmt.Sprintf("%s    Text(%s)\n", indent, strlit.StringExpr(w.TextExpr)))
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case "icon":
		out.WriteString(fmt.Sprintf("%sIcon(imageVector = Icons.Filled.%s, contentDescription = null)\n", indent, kotlinIconName(exprSingleValue(w.TextExpr))))

	case "listtile":
		if len(w.Actions) > 0 {
			out.WriteString(fmt.Sprintf("%sListItem(\n", indent))
			out.WriteString(fmt.Sprintf("%s    modifier = Modifier.clickable {\n", indent))
			g.renderComposeActions(out, w.Actions, indent+"        ")
			out.WriteString(fmt.Sprintf("%s    },\n", indent))
		} else {
			out.WriteString(fmt.Sprintf("%sListItem(\n", indent))
		}
		out.WriteString(fmt.Sprintf("%s    headlineContent = { Text(%s) },\n", indent, strlit.StringExpr(w.TextExpr)))
		if len(w.SubExpr) > 0 {
			out.WriteString(fmt.Sprintf("%s    supportingContent = { Text(%s) },\n", indent, strlit.StringExpr(w.SubExpr)))
		}
		if ic := w.Props["icon"]; ic != "" {
			out.WriteString(fmt.Sprintf("%s    leadingContent = { Icon(imageVector = Icons.Filled.%s, contentDescription = null) },\n", indent, kotlinIconName(ic)))
		}
		if tr := w.Props["trailing"]; tr != "" {
			out.WriteString(fmt.Sprintf("%s    trailingContent = { Icon(imageVector = Icons.Filled.%s, contentDescription = null) },\n", indent, kotlinIconName(tr)))
		}
		out.WriteString(fmt.Sprintf("%s)\n", indent))

	case "divider":
		out.WriteString(fmt.Sprintf("%sHorizontalDivider()\n", indent))

	case "sizedbox", "spacer":
		h := w.Props["height"]
		if h == "" {
			h = "12"
		}
		out.WriteString(fmt.Sprintf("%sSpacer(modifier = Modifier.height(%s))\n", indent, kotlinDp(h)))

	case "progress":
		if w.Props["kind"] == "circular" {
			out.WriteString(fmt.Sprintf("%sCircularProgressIndicator()\n", indent))
		} else {
			val := strlit.CodeExpr(w.TextExpr)
			out.WriteString(fmt.Sprintf("%sLinearProgressIndicator(progress = { (%s).toFloat() / 100f })\n", indent, val))
		}

	case "input":
		out.WriteString(fmt.Sprintf("%sOutlinedTextField(\n", indent))
		out.WriteString(fmt.Sprintf("%s    value = %s,\n", indent, w.BindState))
		out.WriteString(fmt.Sprintf("%s    onValueChange = { %s = it },\n", indent, w.BindState))
		out.WriteString(fmt.Sprintf("%s    label = { Text(%s) },\n", indent, strlit.Quoted(w.Placeholder)))
		out.WriteString(fmt.Sprintf("%s    modifier = Modifier.fillMaxWidth()\n", indent))
		out.WriteString(fmt.Sprintf("%s)\n", indent))

	case "switch_toggle":
		out.WriteString(fmt.Sprintf("%sRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {\n", indent))
		out.WriteString(fmt.Sprintf("%s    Switch(checked = %s, onCheckedChange = { %s = it })\n", indent, w.BindState, w.BindState))
		out.WriteString(fmt.Sprintf("%s    Text(%s)\n%s}\n", indent, strlit.Quoted(w.Placeholder), indent))

	case "checkbox":
		out.WriteString(fmt.Sprintf("%sRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {\n", indent))
		out.WriteString(fmt.Sprintf("%s    Checkbox(checked = %s, onCheckedChange = { %s = it })\n", indent, w.BindState, w.BindState))
		out.WriteString(fmt.Sprintf("%s    Text(%s)\n%s}\n", indent, strlit.Quoted(w.Placeholder), indent))

	case "slider":
		min := w.Props["min"]
		if min == "" {
			min = "0"
		}
		max := w.Props["max"]
		if max == "" {
			max = "100"
		}
		out.WriteString(fmt.Sprintf("%sSlider(\n", indent))
		out.WriteString(fmt.Sprintf("%s    value = %s.toFloat(),\n", indent, w.BindState))
		out.WriteString(fmt.Sprintf("%s    valueRange = %sf..%sf,\n", indent, min, max))
		if g.states[w.BindState] == "float" {
			out.WriteString(fmt.Sprintf("%s    onValueChange = { %s = it }\n", indent, w.BindState))
		} else {
			out.WriteString(fmt.Sprintf("%s    onValueChange = { %s = it.toInt() }\n", indent, w.BindState))
		}
		out.WriteString(fmt.Sprintf("%s)\n", indent))

	case "dropdown":
		idx := g.dropdownIdx
		g.dropdownIdx++
		expandedVar := fmt.Sprintf("ddExpanded%d", idx)
		out.WriteString(fmt.Sprintf("%svar %s by remember { mutableStateOf(false) }\n", indent, expandedVar))
		out.WriteString(fmt.Sprintf("%sExposedDropdownMenuBox(expanded = %s, onExpandedChange = { %s = it }) {\n", indent, expandedVar, expandedVar))
		out.WriteString(fmt.Sprintf("%s    OutlinedTextField(value = %s, onValueChange = {}, readOnly = true, trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded = %s) }, modifier = Modifier.menuAnchor().fillMaxWidth())\n", indent, w.BindState, expandedVar))
		out.WriteString(fmt.Sprintf("%s    ExposedDropdownMenu(expanded = %s, onDismissRequest = { %s = false }) {\n", indent, expandedVar, expandedVar))
		for _, opt := range w.Options {
			out.WriteString(fmt.Sprintf("%s        DropdownMenuItem(text = { Text(%s) }, onClick = { %s = %s; %s = false })\n", indent, strlit.Quoted(opt), w.BindState, strlit.Quoted(opt), expandedVar))
		}
		out.WriteString(fmt.Sprintf("%s    }\n%s}\n", indent, indent))

	case "button", "fab", "icon_button":
		if w.Kind == "fab" {
			out.WriteString(fmt.Sprintf("%sFloatingActionButton(onClick = {\n", indent))
			g.renderComposeActions(out, w.Actions, indent+"    ")
			out.WriteString(fmt.Sprintf("%s}) {\n", indent))
			out.WriteString(fmt.Sprintf("%s    Icon(imageVector = Icons.Filled.%s, contentDescription = null)\n", indent, kotlinIconName(exprSingleValue(w.TextExpr))))
			out.WriteString(fmt.Sprintf("%s}\n", indent))
			return
		}
		if w.Kind == "icon_button" {
			out.WriteString(fmt.Sprintf("%sIconButton(onClick = {\n", indent))
			g.renderComposeActions(out, w.Actions, indent+"    ")
			out.WriteString(fmt.Sprintf("%s}) {\n", indent))
			out.WriteString(fmt.Sprintf("%s    Icon(imageVector = Icons.Filled.%s, contentDescription = null)\n", indent, kotlinIconName(exprSingleValue(w.TextExpr))))
			out.WriteString(fmt.Sprintf("%s}\n", indent))
			return
		}
		out.WriteString(fmt.Sprintf("%sButton(onClick = {\n", indent))
		g.renderComposeActions(out, w.Actions, indent+"    ")
		out.WriteString(fmt.Sprintf("%s}) {\n", indent))
		out.WriteString(fmt.Sprintf("%s    Text(text = %s)\n", indent, strlit.StringExpr(w.TextExpr)))
		out.WriteString(fmt.Sprintf("%s}\n", indent))
	}
}

func (g *composeGen) renderComposeSingleChild(out *strings.Builder, children []ast.WidgetNode, indent string) {
	if len(children) == 1 {
		g.renderComposeWidget(out, children[0], indent)
		return
	}
	out.WriteString(fmt.Sprintf("%sColumn(verticalArrangement = Arrangement.spacedBy(8.dp)) {\n", indent))
	for _, ch := range children {
		g.renderComposeWidget(out, ch, indent+"    ")
	}
	out.WriteString(fmt.Sprintf("%s}\n", indent))
}

func (g *composeGen) renderComposeActions(out *strings.Builder, actions []ast.ActionNode, indent string) {
	for _, act := range actions {
		switch act.Kind {
		case "assign":
			out.WriteString(fmt.Sprintf("%s%s = %s\n", indent, act.TargetVar, act.ExprValue))
		case "list_add":
			out.WriteString(fmt.Sprintf("%s%s.add((%s).toString())\n", indent, act.TargetVar, act.ExprValue))
		case "list_remove":
			out.WriteString(fmt.Sprintf("%s{ val _i = %s; if (_i >= 0 && _i < %s.size) %s.removeAt(_i) }\n", indent, act.ExprValue, act.TargetVar, act.TargetVar))
		case "toast", "snackbar":
			out.WriteString(fmt.Sprintf("%sToast.makeText(context, %s, Toast.LENGTH_SHORT).show()\n", indent, strlit.StringExpr(act.MsgExpr)))
		case "dialog":
			// No dialog scaffold in the preview target: show title + message as a toast.
			combined := append(append([]ast.ExprPart{}, act.TitleExpr...), ast.ExprPart{IsLiteral: true, Value: ": "})
			combined = append(combined, act.MsgExpr...)
			out.WriteString(fmt.Sprintf("%sToast.makeText(context, %s, Toast.LENGTH_SHORT).show()\n", indent, strlit.StringExpr(combined)))
		case "navigate":
			out.WriteString(fmt.Sprintf("%scurrentScreen = %s\n", indent, strlit.Quoted(act.ExprValue)))
			if g.inDrawer {
				out.WriteString(fmt.Sprintf("%sscope.launch { drawerState.close() }\n", indent))
			}
		case "navigate_back":
			out.WriteString(fmt.Sprintf("%scurrentScreen = %s\n", indent, strlit.Quoted(g.firstScreen)))
			if g.inDrawer {
				out.WriteString(fmt.Sprintf("%sscope.launch { drawerState.close() }\n", indent))
			}
		case "if":
			out.WriteString(fmt.Sprintf("%sif (%s) {\n", indent, act.CondExpr))
			g.renderComposeActions(out, act.ThenActions, indent+"    ")
			if len(act.ElseActions) > 0 {
				out.WriteString(fmt.Sprintf("%s} else {\n", indent))
				g.renderComposeActions(out, act.ElseActions, indent+"    ")
			}
			out.WriteString(fmt.Sprintf("%s}\n", indent))
		}
	}
}

func (g *composeGen) composeContainerModifier(w ast.WidgetNode) string {
	var parts []string
	if pad := w.Props["padding"]; pad != "" {
		parts = append(parts, fmt.Sprintf(".padding(%s)", kotlinDp(pad)))
	}
	if bg := w.Props["bg"]; bg != "" {
		parts = append(parts, fmt.Sprintf(".background(%s)", kotlinColor(bg)))
	}
	return strings.Join(parts, "")
}

func (g *composeGen) composeTextStyle(w ast.WidgetNode) string {
	var parts []string
	if size := w.Props["size"]; size != "" {
		parts = append(parts, fmt.Sprintf("fontSize = %s.sp", size))
	}
	if weight := w.Props["weight"]; weight == "bold" || weight == "semibold" || weight == "w600" {
		if weight == "bold" {
			parts = append(parts, "fontWeight = FontWeight.Bold")
		} else {
			parts = append(parts, "fontWeight = FontWeight.SemiBold")
		}
	}
	if col := w.Props["color"]; col != "" {
		parts = append(parts, fmt.Sprintf("color = %s", kotlinColor(col)))
	}
	if len(parts) == 0 {
		return ""
	}
	return ", " + strings.Join(parts, ", ")
}

func kotlinDp(v string) string {
	return v + ".dp"
}

func kotlinIconName(snake string) string {
	var sb strings.Builder
	capNext := true
	for _, r := range snake {
		if r == '_' {
			capNext = true
			continue
		}
		if capNext {
			sb.WriteString(strings.ToUpper(string(r)))
			capNext = false
		} else {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

